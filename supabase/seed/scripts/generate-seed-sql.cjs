/**
 * Generate SQL migration from JSON seed data files
 * CommonJS version for Node.js
 */

const fs = require('fs');
const path = require('path');

// SQL escape helper
function escapeSql(value) {
  if (value === null || value === undefined) {
    return 'null';
  }
  if (typeof value === 'string') {
    return `'${value.replace(/'/g, "''")}'`;
  }
  if (typeof value === 'number' || typeof value === 'boolean') {
    return String(value);
  }
  if (typeof value === 'object') {
    return `'${JSON.stringify(value).replace(/'/g, "''")}'::jsonb`;
  }
  return String(value);
}

// Array to PostgreSQL array literal
function arrayToSql(arr) {
  if (!arr) return 'null';
  if (arr.length === 0) return "'{}'";

  // For text arrays
  if (typeof arr[0] === 'string') {
    return `'{${arr.map(s => `"${s.replace(/"/g, '\\"')}"`).join(',')}}'`;
  }

  // For numeric arrays
  return `'{${arr.join(',')}}'`;
}

function generateSql() {
  const seedDir = path.join(process.cwd(), 'supabase', 'seed');

  // Read JSON files
  const skillTags = JSON.parse(
    fs.readFileSync(path.join(seedDir, 'skill_tags.json'), 'utf-8')
  );
  const regions = JSON.parse(
    fs.readFileSync(path.join(seedDir, 'regions.json'), 'utf-8')
  );
  const factCards = JSON.parse(
    fs.readFileSync(path.join(seedDir, 'fact_cards.json'), 'utf-8')
  );

  let sql = `-- Seed data for Geolet MVP
-- Generated from JSON files by generate-seed-sql.cjs
-- DO NOT EDIT THIS FILE MANUALLY - Edit JSON files instead and regenerate

`;

  // Generate skill_tags inserts
  sql += `-- Skill Tags (${skillTags.length} records)\n`;
  sql += `INSERT INTO skill_tags (key, family, country, meta) VALUES\n`;
  sql += skillTags.map((tag, idx) => {
    const values = [
      escapeSql(tag.key),
      escapeSql(tag.family),
      escapeSql(tag.country),
      escapeSql(tag.meta)
    ];
    const suffix = idx === skillTags.length - 1 ? ';' : ',';
    return `  (${values.join(', ')})${suffix}`;
  }).join('\n');
  sql += '\n\n';

  // Generate regions inserts
  sql += `-- Regions (${regions.length} records)\n`;
  sql += `INSERT INTO regions (key, kind, name, country, geometry, centroid_lonlat, bbox, meta) VALUES\n`;
  sql += regions.map((region, idx) => {
    const values = [
      escapeSql(region.key),
      escapeSql(region.kind),
      escapeSql(region.name),
      escapeSql(region.country),
      escapeSql(region.geometry),
      arrayToSql(region.centroid_lonlat),
      arrayToSql(region.bbox),
      escapeSql(region.meta)
    ];
    const suffix = idx === regions.length - 1 ? ';' : ',';
    return `  (${values.join(', ')})${suffix}`;
  }).join('\n');
  sql += '\n\n';

  // Generate fact_cards inserts
  sql += `-- Fact Cards (${factCards.length} records)\n`;
  sql += `INSERT INTO fact_cards (type, payload, primary_tags, difficulty, answer) VALUES\n`;
  sql += factCards.map((card, idx) => {
    const values = [
      escapeSql(card.type),
      escapeSql(card.payload),
      arrayToSql(card.primary_tags),
      card.difficulty,
      escapeSql(card.answer)
    ];
    const suffix = idx === factCards.length - 1 ? ';' : ',';
    return `  (${values.join(', ')})${suffix}`;
  }).join('\n');
  sql += '\n';

  // Write to migration file
  const timestamp = new Date().toISOString().replace(/[-:]/g, '').split('.')[0].replace('T', '');
  const migrationPath = path.join(
    process.cwd(),
    'supabase',
    'migrations',
    `${timestamp}_seed_initial_data.sql`
  );

  fs.writeFileSync(migrationPath, sql);

  console.log(`✅ Generated seed migration: ${migrationPath}`);
  console.log(`   - ${skillTags.length} skill_tags`);
  console.log(`   - ${regions.length} regions`);
  console.log(`   - ${factCards.length} fact_cards`);
  console.log(`\n⚠️  Remember to run migrations in order:`);
  console.log(`   1. First: 20251109170000_make_geometry_nullable.sql`);
  console.log(`   2. Then: ${timestamp}_seed_initial_data.sql`);
}

generateSql();
